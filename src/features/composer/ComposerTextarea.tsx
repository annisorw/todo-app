import { useEffect, useRef } from 'react'
import type { RefObject } from 'react'
import { MAX_TITLE_LENGTH } from '../../domain/limits'
import { cn } from '../../lib/cn'
import type { ComposerFormController } from './useComposerForm'

export interface ComposerTextareaProps {
  form: ComposerFormController
  errorId: string
  autoFocus?: boolean
  className?: string
  /**
   * Lets the caller hold the field's node — the desktop panel passes its own
   * ref so the global `N` shortcut can focus it (design-spec 6.3). Omitted,
   * the component keeps its private one; either way there is exactly one,
   * because the autosize effect below reads whichever is in play.
   */
  fieldRef?: RefObject<HTMLTextAreaElement | null>
}

/**
 * The textarea shared by the desktop panel (`Composer`) and the mobile sheet
 * (`ComposerSheet`): aria wiring and autosize-by-`scrollHeight` live here once
 * so neither call site reimplements them. `errorId` is generated by the
 * caller (not here) because the desktop panel and the sheet render from the
 * same `useComposerForm()` instance at once — one of them just CSS-hidden —
 * so each needs its own id to avoid a duplicate DOM id across the two trees.
 *
 * This textarea suppresses its own native focus ring: both call sites
 * replace it with their own treatment on the surrounding field — the card
 * glow on desktop, the bordered field box in the sheet (design-spec 3.7/3.8).
 * See `focusRing.node.test.ts` for the allowlist entry this suppression has
 * to keep satisfying.
 */
export function ComposerTextarea({ form, errorId, autoFocus, className, fieldRef }: ComposerTextareaProps) {
  const ownRef = useRef<HTMLTextAreaElement>(null)
  const ref = fieldRef ?? ownRef

  useEffect(() => {
    const node = ref.current
    if (node === null) return
    node.style.height = 'auto'
    node.style.height = `${String(node.scrollHeight)}px`
    // `ref` is one of two stable ref objects, picked once per mount; it is in
    // the list only because the linter cannot see that.
  }, [form.title, ref])

  return (
    <textarea
      ref={ref}
      autoFocus={autoFocus}
      rows={1}
      value={form.title}
      maxLength={MAX_TITLE_LENGTH}
      placeholder="Что нужно сделать?"
      aria-label="Текст новой задачи"
      onChange={(event) => form.setTitle(event.target.value)}
      onFocus={form.handleFocus}
      onBlur={form.handleBlur}
      onKeyDown={form.handleKeyDown}
      aria-describedby={form.error ? errorId : undefined}
      aria-invalid={form.error !== null || undefined}
      className={cn(
        'resize-none bg-transparent text-body-lg text-primary placeholder:text-tertiary focus-visible:outline-none',
        className,
      )}
    />
  )
}
